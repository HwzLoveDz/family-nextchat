import "server-only";
import { getMigrations } from "better-auth/db/migration";
import { createFamilyAuth } from "./auth";
import { transaction } from "./db";

export const FAMILY_SCHEMA_SQL = String.raw`-- Application tables. Better Auth's own schema is generated by its migration API first.
-- Serialize session creation with account disable/revocation, including auth-library paths.
CREATE OR REPLACE FUNCTION family_require_approved_session() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE current_status text;
BEGIN
  SELECT status INTO current_status FROM "user" WHERE id=NEW."userId" FOR SHARE;
  IF current_status IS DISTINCT FROM 'approved' THEN
    RAISE EXCEPTION 'ACCOUNT_UNAVAILABLE' USING ERRCODE='42501';
  END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS family_session_approval ON "session";
CREATE TRIGGER family_session_approval BEFORE INSERT OR UPDATE OF "userId" ON "session"
FOR EACH ROW EXECUTE FUNCTION family_require_approved_session();
CREATE TABLE IF NOT EXISTS family_setup (
  id integer PRIMARY KEY CHECK (id = 1),
  initialized boolean NOT NULL DEFAULT false,
  admin_id text REFERENCES "user"(id),
  initialized_at timestamptz
);
INSERT INTO family_setup(id) VALUES(1) ON CONFLICT DO NOTHING;
CREATE TABLE IF NOT EXISTS family_invite (
  id uuid PRIMARY KEY,
  token_hash text NOT NULL UNIQUE,
  created_by text NOT NULL REFERENCES "user"(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL,
  used_by text UNIQUE REFERENCES "user"(id),
  used_at timestamptz,
  revoked_at timestamptz
);
CREATE TABLE IF NOT EXISTS family_chat (
  id uuid PRIMARY KEY,
  user_id text NOT NULL REFERENCES "user"(id),
  title text NOT NULL DEFAULT '新对话',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz
);
CREATE INDEX IF NOT EXISTS family_chat_owner ON family_chat(user_id, updated_at DESC);
CREATE TABLE IF NOT EXISTS family_generation (
  id uuid PRIMARY KEY,
  user_id text NOT NULL REFERENCES "user"(id),
  chat_id uuid NOT NULL REFERENCES family_chat(id),
  request_id text NOT NULL,
  request_hash text NOT NULL,
  model text NOT NULL,
  state text NOT NULL CHECK (state IN ('running','complete','partial','error')),
  started_at timestamptz NOT NULL DEFAULT now(),
  finished_at timestamptz,
  input_tokens bigint,
  output_tokens bigint,
  usage_source text NOT NULL DEFAULT 'unknown' CHECK (usage_source IN ('unknown','reported')),
  UNIQUE(user_id, request_id),
  CHECK (input_tokens IS NULL OR input_tokens >= 0),
  CHECK (output_tokens IS NULL OR output_tokens >= 0)
);
CREATE UNIQUE INDEX IF NOT EXISTS family_one_generation_per_chat ON family_generation(chat_id) WHERE state = 'running';
CREATE INDEX IF NOT EXISTS family_generation_owner ON family_generation(user_id, started_at);
CREATE TABLE IF NOT EXISTS family_message (
  id uuid PRIMARY KEY,
  chat_id uuid NOT NULL REFERENCES family_chat(id),
  generation_id uuid NOT NULL REFERENCES family_generation(id),
  position bigint GENERATED ALWAYS AS IDENTITY,
  role text NOT NULL CHECK (role IN ('user','assistant')),
  content text NOT NULL,
  status text NOT NULL CHECK (status IN ('complete','streaming','partial','error')),
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(generation_id, role)
);
CREATE INDEX IF NOT EXISTS family_message_chat ON family_message(chat_id, position);
CREATE TABLE IF NOT EXISTS family_activity (
  user_id text PRIMARY KEY REFERENCES "user"(id),
  last_seen_at timestamptz,
  last_heartbeat_at timestamptz,
  active_seconds bigint NOT NULL DEFAULT 0 CHECK (active_seconds >= 0)
);
CREATE TABLE IF NOT EXISTS family_activity_event (
  user_id text NOT NULL REFERENCES "user"(id),
  event_id text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY(user_id, event_id)
);
CREATE TABLE IF NOT EXISTS family_admin_audit (
  id uuid PRIMARY KEY,
  actor_id text NOT NULL REFERENCES "user"(id),
  action text NOT NULL,
  target_user_id text REFERENCES "user"(id),
  target_chat_id uuid REFERENCES family_chat(id),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS family_rate_limit (
  key text PRIMARY KEY,
  count integer NOT NULL,
  expires_at timestamptz NOT NULL
);
DO $$ BEGIN
  IF NOT EXISTS(SELECT 1 FROM pg_constraint WHERE conname = 'family_user_status' AND connamespace = current_schema()::regnamespace) THEN
    ALTER TABLE "user" ADD CONSTRAINT family_user_status CHECK(status IN ('pending','approved','disabled'));
  END IF;
END $$;`;

/** Explicit bootstrap/migration only. Never run DDL during a normal request. */
export async function ensureFamilySchema() {
  await transaction(async (client) => {
    await client.query("SELECT pg_advisory_xact_lock(714209830)");
    const auth = createFamilyAuth(client);
    const migration = await getMigrations(auth.options);
    await migration.runMigrations();
    await client.query(FAMILY_SCHEMA_SQL);
  });
}
